import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import Link from 'next/link';
import { ArrowRight, Check, X } from 'lucide-react';
import { standardBySlug, slugFor } from '@/lib/ptStandards';
import { judge, summarise, decodeAnswers, encodeAnswers, verdictHeadline } from '@/lib/standardsShare';

/**
 * Somebody else's result, opened from a link.
 *
 * The share loop's landing spot. A stranger arrives because a friend posted
 * "I passed the Marine PFT", sees the actual numbers, and is one tap from
 * finding out his own. That second tap is the whole reason this page exists,
 * so the call to action is the test, not the app.
 *
 * Stateless: everything on screen comes out of the query string. Nothing is
 * stored, nothing is looked up, and the page carries no information about
 * who took the test — just the numbers they chose to publish.
 */

export const dynamic = 'force-dynamic';

type Props = {
  params: Promise<{ unit: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
};

const pick = (sp: Record<string, string | string[] | undefined>) => (k: string) => {
  const v = sp[k];
  return typeof v === 'string' ? v : null;
};

export async function generateMetadata({ params, searchParams }: Props): Promise<Metadata> {
  const { unit } = await params;
  const s = standardBySlug(unit);
  if (!s) return { title: 'Standard not found' };

  const sp = await searchParams;
  const answers = decodeAnswers(pick(sp));
  const verdicts = judge(s, answers);
  const title = verdictHeadline(s, verdicts);
  const description = `${s.resultTitle}. See the numbers, then find out where you stand — free, no account.`;

  // The card is generated by a route rather than the opengraph-image file
  // convention, because that convention never receives the query string the
  // scores live in. Carrying them here is what puts real numbers in the feed.
  const img = new URLSearchParams(encodeAnswers(answers));
  img.set('unit', slugFor(s.id));
  const imageUrl = `/api/standards/og?${img.toString()}`;

  return {
    title,
    description,
    // A shared result is one person's numbers, not a page worth indexing;
    // the unit page is the canonical thing for search.
    robots: { index: false, follow: true },
    alternates: { canonical: `/standards/${slugFor(s.id)}` },
    openGraph: { title, description, type: 'article', images: [{ url: imageUrl, width: 1200, height: 630 }] },
    twitter: { card: 'summary_large_image', title, description, images: [imageUrl] },
  };
}

export default async function SharedResultPage({ params, searchParams }: Props) {
  const { unit } = await params;
  const standard = standardBySlug(unit);
  if (!standard) notFound();

  const verdicts = judge(standard, decodeAnswers(pick(await searchParams)));
  const { passedAll, answered, failures } = summarise(verdicts);
  const attempted = verdicts.filter((v) => v.yours !== '—');
  const slug = slugFor(standard.id);

  return (
    <div className="max-w-2xl mx-auto px-5 py-12">
      <p className="text-[11px] font-bold uppercase tracking-[0.2em] text-accent">
        {standard.flag} {standard.resultTitle}
      </p>
      <h1 className="text-3xl sm:text-4xl font-black text-white mt-3 leading-tight text-balance">
        {verdictHeadline(standard, verdicts)}
      </h1>

      {answered === 0 ? (
        <p className="text-text-secondary mt-4">
          This link has no scores on it. Take the test yourself and see where you stand.
        </p>
      ) : (
        <>
          <p className="text-text-secondary mt-4">
            {passedAll
              ? `Every event in the ${standard.label} test, cleared.`
              : `${attempted.length - failures.length} of ${attempted.length} events cleared against the published standard.`}
          </p>

          <div className="mt-7 rounded-2xl border border-white/10 overflow-hidden">
            {attempted.map((v, i) => (
              <div
                key={v.key}
                className={`flex items-center gap-3 px-4 py-3.5 ${i > 0 ? 'border-t border-white/8' : ''}`}
              >
                <span
                  className={`w-7 h-7 rounded-lg flex items-center justify-center flex-shrink-0 ${
                    v.passed ? 'bg-success/15 text-success' : 'bg-accent/15 text-accent'
                  }`}
                >
                  {v.passed ? <Check className="w-4 h-4" /> : <X className="w-4 h-4" />}
                </span>
                <span className="flex-1 min-w-0 text-sm font-semibold text-white truncate">{v.label}</span>
                <span className="text-sm tabular-nums text-white font-bold">{v.yours}</span>
                <span className="text-xs tabular-nums text-text-tertiary whitespace-nowrap">needs {v.target}</span>
              </div>
            ))}
          </div>
        </>
      )}

      {/* The reason this page exists: the next person's test. */}
      <div className="mt-8 rounded-2xl border border-accent/30 bg-accent/8 p-5">
        <p className="text-base font-extrabold text-white">Where would you stand?</p>
        <p className="text-sm text-text-secondary mt-1.5">
          Enter your own numbers against the same published standard. Free, no account, about ninety seconds.
        </p>
        <Link
          href={`/standards/${slug}`}
          className="mt-4 inline-flex items-center gap-2 h-11 px-5 rounded-xl bg-accent text-black font-extrabold text-sm"
        >
          Take the {standard.label} test <ArrowRight className="w-4 h-4" />
        </Link>
      </div>

      <p className="text-[11px] text-text-tertiary mt-6 leading-relaxed">
        {standard.source} Passing every event here does not mean you would pass selection — it means you would not be
        sent home on the fitness test.
      </p>

      <Link href="/standards" className="inline-block mt-6 text-sm text-text-secondary hover:text-white">
        See every standard
      </Link>
    </div>
  );
}
